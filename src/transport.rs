//! A bounded, one-session TLS proxy for loopback integration tests.
//!
//! Each leg has a private trust store and a provisioned peer certificate.
//! TLS Server Name Indication (SNI) selects a configured route. Peer identity
//! comes from the provisioned certificate and verified chain.

use openssl::hash::MessageDigest;
use openssl::ssl::{
    NameType, Ssl, SslContext, SslContextBuilder, SslFiletype, SslMethod, SslOptions,
    SslSessionCacheMode, SslVerifyMode, SslVersion,
};
use openssl::x509::X509;
use std::{fs, io, net::SocketAddr, path::Path, pin::Pin, time::Duration};
use tokio::{io::copy_bidirectional, net::TcpStream, time::timeout};
use tokio_openssl::SslStream;

/// A mutual TLS endpoint with a dedicated trust anchor and an exact peer leaf pin.
pub struct TlsEndpoint {
    context: SslContext,
}

impl TlsEndpoint {
    /// Load an endpoint from the test PKI generated by `cargo run -p xtask -- gen-pki`.
    ///
    /// Select `han/cls` ↔ `han/smgw` or `wan/smgw` ↔ `wan/aemt`.
    /// The peer's chain file supplies the provisioned leaf pin. Verifying its chain
    /// at connection time also enforces certificate purpose and validity.
    pub fn load(dir: &Path, domain: &str, role: &str, peer: &str) -> io::Result<Self> {
        if !matches!(
            (domain, role, peer),
            ("han", "cls", "smgw")
                | ("han", "smgw", "cls")
                | ("wan", "smgw", "aemt")
                | ("wan", "aemt", "smgw")
        ) {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "unknown PKI role pair",
            ));
        }
        let dir = dir.join(domain);
        let chain = fs::read(dir.join(format!("{peer}.chain.pem")))?;
        let pin = X509::from_pem(&chain)?.digest(MessageDigest::sha256())?;
        let mut context = SslContextBuilder::new(SslMethod::tls())?;
        context.set_min_proto_version(Some(SslVersion::TLS1_2))?;
        context.set_max_proto_version(Some(SslVersion::TLS1_2))?;
        context.set_groups_list("brainpoolP256r1")?;
        context.set_cipher_list("ECDHE-ECDSA-AES128-GCM-SHA256")?;
        context.set_options(
            SslOptions::NO_RENEGOTIATION | SslOptions::NO_TICKET | SslOptions::NO_COMPRESSION,
        );
        context.set_session_cache_mode(SslSessionCacheMode::OFF);
        context.set_ca_file(dir.join("root.pem"))?;
        context.set_certificate_chain_file(dir.join(format!("{role}.chain.pem")))?;
        context.set_private_key_file(dir.join(format!("{role}.key.pem")), SslFiletype::PEM)?;
        context.check_private_key()?;
        context.set_verify_depth(2);
        context.set_verify_callback(
            SslVerifyMode::PEER | SslVerifyMode::FAIL_IF_NO_PEER_CERT,
            move |valid, chain| {
                valid
                    && (chain.error_depth() != 0
                        || chain.current_cert().is_some_and(|leaf| {
                            leaf.digest(MessageDigest::sha256())
                                .is_ok_and(|seen| seen.as_ref() == pin.as_ref())
                        }))
            },
        );
        Ok(Self {
            context: context.build(),
        })
    }

    /// Dials the literal loopback address and sends SNI within one setup budget.
    pub async fn connect(
        &self,
        address: SocketAddr,
        sni: &str,
        budget: Duration,
    ) -> io::Result<SslStream<TcpStream>> {
        loopback(address)?;
        dns_name(sni)?;
        let mut ssl = Ssl::new(&self.context)?;
        ssl.set_hostname(sni)?;
        timeout(budget, async {
            let tcp = TcpStream::connect(address).await?;
            let mut tls = SslStream::new(ssl, tcp)?;
            Pin::new(&mut tls)
                .connect()
                .await
                .map_err(io::Error::other)?;
            Ok(tls)
        })
        .await?
    }

    /// Accepts a mutually authenticated TLS session on an existing loopback socket.
    pub async fn accept(
        &self,
        tcp: TcpStream,
        budget: Duration,
    ) -> io::Result<SslStream<TcpStream>> {
        loopback(tcp.local_addr()?)?;
        loopback(tcp.peer_addr()?)?;
        let mut tls = SslStream::new(Ssl::new(&self.context)?, tcp)?;
        timeout(budget, Pin::new(&mut tls).accept())
            .await?
            .map_err(io::Error::other)?;
        Ok(tls)
    }
}

fn loopback(address: SocketAddr) -> io::Result<()> {
    if address.ip().is_loopback() {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "the simulator requires a loopback address",
        ))
    }
}

fn dns_name(name: &str) -> io::Result<()> {
    let valid = name.len() <= 253
        && name.parse::<std::net::IpAddr>().is_err()
        && name.split('.').all(|label| {
            !label.is_empty()
                && label.len() <= 63
                && !label.starts_with('-')
                && !label.ends_with('-')
                && label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        });
    if valid {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "expected a DNS name for TLS SNI",
        ))
    }
}

/// A single authorized HAN-to-WAN route. A mutable borrow admits one session at a time.
pub struct SmgwProxy {
    han: TlsEndpoint,
    wan: TlsEndpoint,
    route: String,
    wan_address: SocketAddr,
    wan_sni: String,
    handshake_timeout: Duration,
    session_timeout: Duration,
}

impl SmgwProxy {
    /// Configures the SNI route and its fixed loopback WAN destination.
    pub fn new(
        han: TlsEndpoint,
        wan: TlsEndpoint,
        route: String,
        wan_address: SocketAddr,
        wan_sni: String,
        handshake_timeout: Duration,
        session_timeout: Duration,
    ) -> io::Result<Self> {
        loopback(wan_address)?;
        dns_name(&route)?;
        dns_name(&wan_sni)?;
        if handshake_timeout.is_zero() || session_timeout.is_zero() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "timeouts must be positive",
            ));
        }
        Ok(Self {
            han,
            wan,
            route,
            wan_address,
            wan_sni,
            handshake_timeout,
            session_timeout,
        })
    }

    /// Authenticates the CLS and authorizes its SNI before opening a WAN socket.
    ///
    /// The session deadline covers both handshakes and relay. Dropping this future
    /// closes the streams. The return value counts plaintext bytes in HAN-to-WAN
    /// and WAN-to-HAN order. Tokio bounds the relay buffer in each direction.
    pub async fn relay(&mut self, tcp: TcpStream) -> io::Result<(u64, u64)> {
        timeout(self.session_timeout, async {
            let mut han = self.han.accept(tcp, self.handshake_timeout).await?;
            let authorized = han
                .ssl()
                .servername(NameType::HOST_NAME)
                .is_some_and(|sni| sni.eq_ignore_ascii_case(&self.route));
            if !authorized {
                return Err(io::Error::new(
                    io::ErrorKind::PermissionDenied,
                    "unknown CLS proxy route",
                ));
            }
            let mut wan = self
                .wan
                .connect(self.wan_address, &self.wan_sni, self.handshake_timeout)
                .await?;
            copy_bidirectional(&mut han, &mut wan).await
        })
        .await?
    }
}
